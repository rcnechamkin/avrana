"""Outermost ASGI middleware: method gate, response hygiene, access log, error containment.

Pure ASGI (no Starlette types) so it sees every response the application produces, including
framework-generated ones (404, 405, 422, 500). Responses generated by the SERVER before the
application runs (uvicorn's 400 for a malformed request line, 431 for oversized headers) cannot
carry these headers; they contain no application data (documented in HOME-APP.md).

  * Methods other than GET and HEAD get 501 before any routing or identity work, for every path
    and every identity, like the portal (http.server answers 501 before looking at groups). The
    body is fixed text and does NOT echo the method.
  * Every response gets Cache-Control: no-store, Referrer-Policy: no-referrer,
    X-Content-Type-Options: nosniff and a strict Content-Security-Policy with no script source.
  * An exception escaping the application becomes a generic 500 page; only the exception CLASS is
    logged, never its message or traceback (those can carry request data), and nothing is
    re-raised into the server's own logger.
  * One structured access line per request: route template, method, status, duration.
"""
from __future__ import annotations

import logging
import time
from typing import Callable

from .logsafe import access_log, app_log, log_event

CSP = (b"default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'; "
       b"frame-ancestors 'none'")
HYGIENE = (
    (b"cache-control", b"no-store"),
    (b"referrer-policy", b"no-referrer"),
    (b"x-content-type-options", b"nosniff"),
    (b"content-security-policy", CSP),
)
_HYGIENE_NAMES = frozenset(name for name, _ in HYGIENE)

NOT_IMPLEMENTED_BODY = (b"<!DOCTYPE HTML>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
                        b"<title>Error response</title>\n</head>\n<body>\n<h1>Error response</h1>\n"
                        b"<p>Error code: 501</p>\n<p>Message: Unsupported method.</p>\n</body>\n</html>\n")


def with_hygiene(headers) -> list:
    return [(k, v) for k, v in headers if k.lower() not in _HYGIENE_NAMES] + list(HYGIENE)


class HygieneMiddleware:
    def __init__(self, app, render_error: Callable[[], bytes]):
        self.app = app
        self._render_error = render_error

    async def __call__(self, scope, receive, send):
        kind = scope["type"]
        if kind == "lifespan":
            await self.app(scope, receive, send)
            return
        if kind != "http":                     # no websockets are served
            if kind == "websocket":
                await send({"type": "websocket.close", "code": 1008})
            return
        started = time.perf_counter()
        state = {"status": 0, "started": False}
        method = scope.get("method", "")

        async def wrapped_send(message):
            if message["type"] == "http.response.start":
                state["status"] = message["status"]
                state["started"] = True
                message = dict(message, headers=with_hygiene(message.get("headers", ())))
            await send(message)

        try:
            if method not in ("GET", "HEAD"):
                scope["avrana_route"] = "method_not_supported"
                await self._plain(wrapped_send, 501, NOT_IMPLEMENTED_BODY, head=False)
            else:
                await self.app(scope, receive, wrapped_send)
        except Exception as exc:
            log_event(app_log, logging.ERROR, "unhandled_error", error_class=type(exc).__name__,
                      route=scope.get("avrana_route", "unmatched"))
            if not state["started"]:
                await self._plain(wrapped_send, 500, self._render_error(), head=(method == "HEAD"))
        finally:
            log_event(access_log, logging.INFO, "request",
                      route=scope.get("avrana_route", "unmatched"), method=method,
                      status=state["status"],
                      duration_ms=round((time.perf_counter() - started) * 1000, 1))

    @staticmethod
    async def _plain(send, status: int, body: bytes, head: bool) -> None:
        await send({"type": "http.response.start", "status": status, "headers": [
            (b"content-type", b"text/html; charset=utf-8"),
            (b"content-length", str(len(body)).encode())]})
        await send({"type": "http.response.body", "body": b"" if head else body})
