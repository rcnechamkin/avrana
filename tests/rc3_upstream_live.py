def abs_json(http_, method, path, token=None, payload=None, expect=200):
    headers = {}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    body = None
    if payload is not None:
        body = json.dumps(payload)
        headers["Content-Type"] = "application/json"
    status, _, data = http_.call(method, path, body=body, headers=headers)
    if status != expect:
        raise SystemExit(f"{method} {path.split('?')[0]}: expected {expect}, got {status}")
    try:
        return json.loads(data) if data else None
    except ValueError:
        return data


def abs_login(http_, username, password):
    return abs_json(http_, "POST", "/login", payload={"username": username, "password": password})


def key_paths(value, prefix=""):
    """Every JSON key path, list positions folded, so two versions' shapes compare without comparing values."""
    out = set()
    if isinstance(value, dict):
        for k, v in value.items():
            # ids used as keys are data, not shape
            key = "<id>" if re.fullmatch(r"[0-9a-f-]{32,36}", k) else k
            out.add(f"{prefix}.{key}")
            out |= key_paths(v, f"{prefix}.{key}")
    elif isinstance(value, list):
        for v in value:
            out |= key_paths(v, f"{prefix}[]")
    return out


def abs_contract(http_, token, state):
    """The routes services/avrana-home/avrana_home/adapters/audiobookshelf.py calls, as shapes."""
    lib, item, member = state["library"], state["item"], state["member_id"]
    shapes = {}
    for label, path in (
        ("users", "/api/users"),
        ("user", f"/api/users/{member}"),
        ("item", f"/api/items/{item}?expanded=1"),
        ("libraries", "/api/libraries"),
        ("search", f"/api/libraries/{lib}/search?q=Proof&limit=5"),
        ("library_items", f"/api/libraries/{lib}/items?sort=addedAt&desc=1&limit=5&minified=1"),
        ("filterdata", f"/api/libraries/{lib}/filterdata"),
    ):
        shapes[label] = sorted(key_paths(abs_json(http_, "GET", path, token)))
    return shapes


def abs_traversal(http_):
    """The advisory's requests, against synthetic files only. Returns {name: (status, body)}."""
    out = {}
    for name, path in (
        # the 2.36.1 shape: a file named <anything>_<width>.<ext>
        ("constrained", "/api/items/..%2F..%2Fsynth/cover?format=txt"),
        # the 2.36.0 shape: a real folder named like *_N.* lets `format` leave it
        ("unconstrained", "/api/items/..%2F..%2Fsynth/cover?width=7&format=d%2F..%2F..%2Fconfig%2Frc3-canary.txt"),
        ("database", "/api/items/..%2F..%2Fsynth/cover?width=7&format=d%2F..%2F..%2Fconfig%2Fabsdatabase.sqlite"),
        ("author", "/api/authors/..%2F..%2Fsynth/image?format=txt"),
        ("prefixed", "/audiobookshelf/api/items/..%2F..%2Fsynth/cover?format=txt"),
    ):
        status, _, data = http_.call("GET", path)
        out[name] = (status, data)
    return out


