class Http:
    """http.client on purpose: it sends the path byte for byte (%2F stays %2F) and never follows a redirect."""

    def __init__(self, base):
        u = urllib.parse.urlsplit(base)
        self.host, self.port = u.hostname, u.port or 80
        self.cookies = {}

    def call(self, method, path, body=None, headers=None, timeout=60):
        h = dict(headers or {})
        if self.cookies:
            h["Cookie"] = "; ".join(f"{k}={v}" for k, v in self.cookies.items())
        conn = http.client.HTTPConnection(self.host, self.port, timeout=timeout)
        try:
            conn.request(method, path, body=body, headers=h)
            r = conn.getresponse()
            data = r.read()
            for k, v in r.getheaders():
                if k.lower() == "set-cookie":
                    name, _, rest = v.partition("=")
                    self.cookies[name.strip()] = rest.split(";", 1)[0]
            return r.status, {k.lower(): v for k, v in r.getheaders()}, data
        finally:
            conn.close()

    def wait(self, path, seconds=240):
        end = time.time() + seconds
        last = None
        while time.time() < end:
            try:
                status, _, _ = self.call("GET", path, timeout=10)
                if status < 500:
                    return status
                last = status
            except OSError as e:
                last = type(e).__name__
            time.sleep(3)
        raise SystemExit(f"service did not answer {path}: last {last}")


