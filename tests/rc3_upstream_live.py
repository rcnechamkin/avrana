def make_epub(path, title):
    """A minimal valid EPUB2. Written here so the fixture is reviewable and needs no binary in Git."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr(zipfile.ZipInfo("mimetype"), "application/epub+zip")
        z.writestr("META-INF/container.xml", (
            '<?xml version="1.0"?><container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">'
            '<rootfiles><rootfile full-path="c.opf" media-type="application/oebps-package+xml"/></rootfiles></container>'))
        z.writestr("c.opf", (
            '<?xml version="1.0"?><package xmlns="http://www.idpf.org/2007/opf" unique-identifier="i" version="2.0">'
            f'<metadata xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:title>{title}</dc:title>'
            '<dc:creator>Proof Author</dc:creator><dc:language>en</dc:language>'
            f'<dc:identifier id="i">urn:rc3:{re.sub(r"[^a-z0-9]", "", title.lower())}</dc:identifier></metadata>'
            '<manifest><item id="t" href="t.xhtml" media-type="application/xhtml+xml"/>'
            '<item id="n" href="n.ncx" media-type="application/x-dtbncx+xml"/></manifest>'
            '<spine toc="n"><itemref idref="t"/></spine></package>'))
        z.writestr("n.ncx", (
            '<?xml version="1.0"?><ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1"><head/>'
            f'<docTitle><text>{title}</text></docTitle><navMap><navPoint id="p" playOrder="1"><navLabel><text>One'
            '</text></navLabel><content src="t.xhtml"/></navPoint></navMap></ncx>'))
        z.writestr("t.xhtml", (
            '<?xml version="1.0" encoding="utf-8"?><html xmlns="http://www.w3.org/1999/xhtml"><head>'
            f'<title>{title}</title></head><body><p>Synthetic fixture.</p></body></html>'))
    with open(path, "wb") as f:
        f.write(buf.getvalue())
    os.chown(path, 1000, 1000)


