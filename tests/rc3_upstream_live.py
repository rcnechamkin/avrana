def form(fields):
    return urllib.parse.urlencode(fields)


FORM = {"Content-Type": "application/x-www-form-urlencoded"}


def cwa_login(base, username, password):
    http_ = Http(base)
    status, _, page = http_.call("GET", "/login")
    token = CSRF.search(page)
    if not token:
        raise SystemExit(f"no CSRF token on /login (status {status})")
    code, headers, _ = http_.call("POST", "/login", form({
        "csrf_token": token.group(1).decode(), "username": username, "password": password, "next": "/",
        "submit": ""}), FORM)
    if code not in (301, 302, 303) or "/login" in headers.get("location", ""):
        raise SystemExit(f"login refused for {username}: {code}")
    return http_


def basic(username, password):
    return {"Authorization": "Basic " + base64.b64encode(f"{username}:{password}".encode()).decode()}


def cwa_titles(http_, username, password):
    code, _, body = http_.call("GET", "/opds/new", headers=basic(username, password))
    return code, body


def cwa_wait_title(base, username, password, title, seconds=240):
    http_ = Http(base)
    end = time.time() + seconds
    code = None
    while time.time() < end:
        code, body = cwa_titles(http_, username, password)
        if code == 200 and title.encode() in body:
            return body
        time.sleep(5)
    check(f"'{title}' appears in the OPDS feed", False, f"last status {code}")
    finish()


